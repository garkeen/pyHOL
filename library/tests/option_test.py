# Tests for the option theory (library/option.pyhol).

"""Option type: partial values as total functions, ported for auto2's
Mapping_Str maps, BST/RBTree search and Dijkstra.

Active: the theory replays VALID, the datatype axioms and the ported
membership lemma are present, and `the` has its defining equation.
Passive: `None = SomeC a` is not derivable, and the failed attempt leaves
the gap count unchanged.
"""

import unittest

from kernel import theory
from core import basic
from core.verify import validate_theory, COMPUTATION_ORACLES


# The ported API: constructors and elimination/case theorems generated by
# `datatype`, the projection `the`, and the `!= None` membership lemma.
API = ['option_induct', 'option_cases', 'option_None_SomeC_neq',
       'option_SomeC_inject', 'the_def_1', 'not_None_iff']


class OptionTheoryTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        import method.stable_state  # noqa: F401  wires the replay pipeline
        basic.load_metadata()

    def testTheoryValidates(self):
        """Every theorem of the theory is VALID after full replay."""
        for fn in basic.get_import_order(['option']):
            basic.load_theory_cache(fn)
        statuses, errors = validate_theory('option', force=True,
                                           trust=COMPUTATION_ORACLES)
        self.assertEqual(set(statuses.values()), {'VALID'}, errors)

    def testApiPresent(self):
        basic.load_theory('option')
        for name in API:
            self.assertIsNotNone(theory.get_theorem(name))

    def testNoneNotSome(self):
        """None = SomeC a is not derivable."""
        from repl.repl import Repl
        repl = Repl()
        repl.cmd_theory('option')
        repl.cmd_var('a \'a')
        repl.cmd_goal('None = SomeC a')
        gaps_before = repl.sps.num_gaps
        repl.run_line('← refl goal=0')
        self.assertTrue(repl.failed)
        self.assertEqual(repl.sps.num_gaps, gaps_before)


if __name__ == '__main__':
    unittest.main()
